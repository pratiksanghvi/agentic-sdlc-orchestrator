"""Stage 8 — Release readiness and the human's final verdict (the orchestrator's success metric).

RR1 readiness checklist ‖ RR2 run metrics → RR3 engineering summary (generated by code from the
audit log) → RR5 verdict: ACCEPT merges run/<id> into master with the next version tag;
REJECT restarts from a chosen stage; END keeps the branch and offers the opted-in rollback.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from langgraph.graph import END, START, StateGraph

from orchestrator.artifacts.approvals import GovernanceError
from orchestrator.execution.git_ops import ProductRepo
from orchestrator.observability.metrics import run_metrics
from orchestrator.observability.node import observed_node
from orchestrator.runtime.context import get_context
from orchestrator.stages.common import (
    END_RUN,
    StageIO,
    ask_choice,
    option,
    ref_of,
    rollback_node,
    to_json,
)

STAGE = "release"
RESTARTABLE = {"1": "requirements", "2": "design", "3": "test_design"}


class ReleaseState(StageIO, total=False):
    checklist: list[dict]
    metrics: dict


def next_version(tags: list[str]) -> str:
    versions = [tuple(int(x) for x in m.groups()) for t in tags
                if (m := re.fullmatch(r"v(\d+)\.(\d+)\.(\d+)", t))]
    if not versions:
        return "v0.1.0"
    major, minor, _ = max(versions)
    return f"v{major}.{minor + 1}.0"


@observed_node(STAGE, "RR1_checklist")
def rr1_checklist(state: ReleaseState) -> dict[str, Any]:
    ctx = get_context(state["run_id"])
    items = []
    for t in ("spec", "stack_adr", "design", "test_plan", "acceptance_suite"):
        try:
            ctx.approvals.require_approved(ref_of(state, t))
            items.append({"item": f"{t} approved and unchanged", "ok": True})
        except (GovernanceError, KeyError) as exc:
            items.append({"item": f"{t} approved and unchanged", "ok": False, "detail": str(exc)})
    report = ctx.store.read_json(ref_of(state, "verification_report"), "report.json")
    items.append({"item": f"acceptance tests {report['tests_passed']}/{report['tests_total']}",
                  "ok": report["passed"]})
    sec = ctx.store.read_json(ref_of(state, "security_report"), "security_report.json")
    items.append({"item": f"security findings: {len(sec['findings'])} (awareness)",
                  "ok": not sec["findings"]})
    warnings = ctx.store.read_json(ref_of(state, "docs"), "warnings.json")
    items.append({"item": f"documentation warnings: {len(warnings)}", "ok": not warnings})
    repo = ProductRepo(Path(state["workspace"]))
    clean = not repo.git("status", "--porcelain")
    items.append({"item": "product working tree clean", "ok": clean})
    return {"checklist": items}


@observed_node(STAGE, "RR2_metrics")
def rr2_metrics(state: ReleaseState) -> dict[str, Any]:
    ctx = get_context(state["run_id"])
    return {"metrics": run_metrics(ctx.log)}


def _summary(ctx, state) -> str:
    spec = ctx.store.read_json(ref_of(state, "spec"), "spec.json")
    stack = ctx.store.read_json(ref_of(state, "stack_adr"), "stack.json")
    report = ctx.store.read_json(ref_of(state, "verification_report"), "report.json")
    sec = ctx.store.read_json(ref_of(state, "security_report"), "security_report.json")
    m = state["metrics"]
    lines = [f"# Engineering summary — {spec['title']}", "", f"Run: `{ctx.run_id}`", "",
             "## Plan & rationale", "",
             f"- Stack: `{stack['chosen_stack']}` — {stack['decision']['rationale'][:600]}",
             f"- {len(spec['functional_requirements'])} functional requirements, "
             f"{len(spec['non_functional_requirements'])} NFRs, "
             f"{len(spec['acceptance_criteria'])} acceptance criteria.", "",
             "## Artifacts", ""]
    for t, ref in sorted(state["artifacts"].items()):
        lines.append(f"- {t}: v{ref['version']} `{ref['hash'][:19]}`")
    lines += ["", "## Validation", "",
              f"- Acceptance tests: {report['tests_passed']}/{report['tests_total']} passed "
              f"(verification attempt {report['attempt']}).",
              f"- Build + unit tests: {'passed' if report['build']['ok'] else 'failed'}.",
              f"- Security/policy findings: {len(sec['findings'])}."]
    lines += ["", "## Readiness checklist", ""]
    lines += [f"- {'✅' if i['ok'] else '⚠️'} {i['item']}" for i in state["checklist"]]
    lines += ["", "## Assumptions", ""] + [f"- {a['id']}: {a['text']}"
                                         for a in spec["assumptions"]] or ["- none"]
    lines += ["", "## Not supported in MVP (requested but not built)", ""]
    lines += [f"- {n['message']}" for n in spec["not_supported"]] or ["- none"]
    lines += ["", "## Risks, trade-offs and limitations", "",
              "- Generated code runs on the host without an OS sandbox.",
              "- SQLite only; single instance; no authentication unless requested.",
              "- SAST and dependency-CVE scanning are not part of this MVP."]
    lines += ["", "## Decision lineage", ""]
    for d in ctx.log.records("decision"):
        data = d["data"]
        what = data.get("gate") or data.get("artifact", {}).get("type", "")
        lines.append(f"- {d['ts'][:19]} {d['name']} {what} {data.get('decision', '')} "
                     f"by {data.get('made_by', '')}".rstrip())
    lines += ["", "## Run metrics", "", "```json", json.dumps(m, indent=2), "```"]
    return "\n".join(lines) + "\n"


@observed_node(STAGE, "RR3_summary")
def rr3_summary(state: ReleaseState) -> dict[str, Any]:
    ctx = get_context(state["run_id"])
    summary = _summary(ctx, state)
    ref = ctx.store.put("engineering_summary", {"ENGINEERING_SUMMARY.md": summary,
                                                "metrics.json": to_json(state["metrics"])},
                        produced_by="RR3")
    return {"artifacts": {"engineering_summary": ref.model_dump()}}


@observed_node(STAGE, "RR5_verdict")
def rr5_verdict(state: ReleaseState) -> dict[str, Any]:
    ctx = get_context(state["run_id"])
    repo = ProductRepo(Path(state["workspace"]))
    version = next_version(repo.tags())
    m = state["metrics"]
    lines = [f"[{'green' if i['ok'] else 'yellow'}]{'✓' if i['ok'] else '!'}[/] {i['item']}"
             for i in state["checklist"]]
    lines += ["", f"LLM calls: {m['llm']['calls']}, cost ${m['llm']['cost_usd']:.2f}, "
              f"fixes: {m['reliability']['fixes']}, end-to-end "
              f"{m['end_to_end_ms'] / 60000:.1f} min",
              f"Summary: {ctx.store.path(ref_of(state, 'engineering_summary'))}",
              f"Product repo: {repo.path} (branch run/{ctx.run_id})", "",
              f"ACCEPT merges into master and tags {version}."]
    decision = ask_choice(
        "final_verdict", "Stage 8 Release · final verdict", "\n".join(lines),
        [option("a", f"ACCEPT — release {version}"),
         option("1", "REJECT — restart from Requirements", needs_reason=True),
         option("2", "REJECT — restart from Design", needs_reason=True),
         option("3", "REJECT — restart from Test Design", needs_reason=True),
         END_RUN])
    approver = "human:" + ctx.config.app.approver_name
    key = decision["key"]
    if key == "a":
        repo.release(ctx.run_id, version)
        ctx.log.append("decision", "final_verdict", decision="ACCEPT", made_by=approver,
                       version=version, head=repo.head())
        return {"status": "completed", "status_reason": f"accepted and released {version}"}
    if key in RESTARTABLE:
        ctx.log.append("decision", "final_verdict", decision="REJECT", made_by=approver,
                       restart_at=RESTARTABLE[key], rationale=decision["reason"])
        return {"status": "restart", "status_reason": decision["reason"],
                "restart_at": RESTARTABLE[key]}
    ctx.log.append("decision", "final_verdict", decision="END", made_by=approver,
                   rationale=decision["reason"])
    return {"status": "ended", "status_reason": decision["reason"]}


def build() -> StateGraph:
    g = StateGraph(ReleaseState, input_schema=StageIO, output_schema=StageIO)
    g.add_node("RR1_checklist", rr1_checklist)
    g.add_node("RR2_metrics", rr2_metrics)
    g.add_node("RR3_summary", rr3_summary)
    g.add_node("RR5_verdict", rr5_verdict)
    g.add_node("rollback", rollback_node(STAGE))
    g.add_edge(START, "RR1_checklist")
    g.add_edge(START, "RR2_metrics")
    g.add_edge(["RR1_checklist", "RR2_metrics"], "RR3_summary")
    g.add_edge("RR3_summary", "RR5_verdict")
    g.add_conditional_edges("RR5_verdict", lambda s: "rollback" if s.get("status") == "ended"
                            else END, ["rollback", END])
    g.add_edge("rollback", END)
    return g
